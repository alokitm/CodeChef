// Time Complexity: O(T)
// Space Complexity: O(1)

#include <bits/stdc++.h>
using namespace std;

int main() {

    // T = number of test cases
    int T;
    cin >> T;

    // Process each test case
    while (T--) {

        // X = number of items
        int X;
        cin >> X;

        // Calculate the maximum number of subscriptions
        cout << 2 * X << endl;
    }

    return 0;
}
